//! XIR -> LLVM IR (textual).
//!
//! Every local lives in an `alloca` in the entry block; LLVM's mem2reg/SROA
//! promote them to registers, so the optimized output is equivalent to
//! hand-written code. Values that need destruction carry a one-bit drop
//! flag, which the optimizer removes whenever ownership is statically known.

use std::collections::{BTreeSet, HashMap, HashSet};
use std::fmt::Write;

use crate::ast::{BinOp, UnOp};
use crate::check::Checker;
use crate::types::{FloatTy, IntTy, Ty};
use crate::xir::{self, BindMode, ConstVal, Expr, ExprKind as K, Func, Intrinsic, LocalId, Pat, Place, Program, Stmt, UseKind};

struct LoopCg {
    id: u32,
    head: String,
    exit: String,
    depth: usize,
    slot: Option<String>,
}

pub struct Codegen<'a> {
    ck: &'a Checker,
    ptr_bits: u32,
    triple: String,
    globals: String,
    out: String,
    strings: HashMap<Vec<u8>, String>,
    glue_done: HashSet<Ty>,
    glue_queue: Vec<Ty>,
    intrinsics: BTreeSet<String>,
    externs: HashMap<String, (Vec<Ty>, Ty, bool)>,
    // per function
    func: Option<&'a Func>,
    body: String,
    allocas: String,
    tmp: u32,
    label: u32,
    terminated: bool,
    scopes: Vec<Vec<LocalId>>,
    loops: Vec<LoopCg>,
}

enum PlacePtr {
    Thin(String),
    /// A fat pointer value `{ ptr, len }` for unsized places.
    Fat(String),
}

pub fn generate(ck: &Checker, prog: &Program, triple: &str, ptr_bits: u32) -> String {
    let mut cg = Codegen {
        ck,
        ptr_bits,
        triple: triple.to_string(),
        globals: String::new(),
        out: String::new(),
        strings: HashMap::new(),
        glue_done: HashSet::new(),
        glue_queue: Vec::new(),
        intrinsics: BTreeSet::new(),
        externs: prog.externs.iter().map(|x| (x.name.clone(), (x.params.clone(), x.ret.clone(), x.variadic))).collect(),
        func: None,
        body: String::new(),
        allocas: String::new(),
        tmp: 0,
        label: 0,
        terminated: false,
        scopes: Vec::new(),
        loops: Vec::new(),
    };
    cg.module(prog)
}

fn quote(name: &str) -> String {
    format!("@\"{}\"", name.replace('"', "\\22"))
}

fn float_lit(v: f64, ty: FloatTy) -> String {
    let v = if ty == FloatTy::F32 { v as f32 as f64 } else { v };
    format!("0x{:016X}", v.to_bits())
}

impl<'a> Codegen<'a> {
    fn module(&mut self, prog: &'a Program) -> String {
        for s in &prog.statics {
            let init = self.const_val(&s.init, &s.ty);
            let kw = if s.mutable { "global" } else { "constant" };
            let _ = writeln!(self.globals, "{} = internal {} {} {}", quote(&s.name), kw, self.llty(&s.ty), init);
        }
        for e in &prog.externs {
            let params: Vec<String> = e.params.iter().map(|t| self.abi_param(t)).collect();
            let mut ps = params.join(", ");
            if e.variadic {
                if !ps.is_empty() {
                    ps.push_str(", ");
                }
                ps.push_str("...");
            }
            let _ = writeln!(self.globals, "declare {} @{}({}) nounwind", self.ret_llty(&e.ret), e.name, ps);
        }
        for f in &prog.funcs {
            self.function(f);
        }
        while let Some(t) = self.glue_queue.pop() {
            self.drop_glue(&t);
        }
        if let Some((name, ret)) = &prog.entry {
            let _ = writeln!(self.out, "define i32 @main() {{");
            if *ret == Ty::Int(IntTy::I32) {
                let _ = writeln!(self.out, "  %r = call i32 {}()\n  ret i32 %r\n}}", quote(name));
            } else {
                let _ = writeln!(self.out, "  call {} {}()\n  ret i32 0\n}}", self.ret_llty(ret), quote(name));
            }
        }
        let mut m = String::new();
        let _ = writeln!(m, "; generated by xeroc");
        let _ = writeln!(m, "target triple = \"{}\"\n", self.triple);
        m.push_str(&self.globals);
        m.push('\n');
        for i in &self.intrinsics {
            let _ = writeln!(m, "{i}");
        }
        m.push('\n');
        m.push_str(&self.out);
        m
    }

    // ------------------------------------------------------------- types

    fn usize_ty(&self) -> String {
        format!("i{}", self.ptr_bits)
    }

    fn llty(&self, t: &Ty) -> String {
        match t {
            Ty::Int(it) => format!("i{}", it.bits(self.ptr_bits)),
            Ty::Float(FloatTy::F32) => "float".into(),
            Ty::Float(FloatTy::F64) => "double".into(),
            Ty::Bool => "i1".into(),
            Ty::Never => "{}".into(),
            Ty::Str | Ty::Slice(_) => "i8".into(),
            Ty::Ref(inner, _) | Ty::Ptr(inner) => {
                if inner.is_unsized() {
                    format!("{{ ptr, {} }}", self.usize_ty())
                } else {
                    "ptr".into()
                }
            }
            Ty::Array(e, n) => format!("[{} x {}]", n, self.llty(e)),
            Ty::Tuple(ts) => self.struct_llty(ts),
            Ty::Adt(id, args) => {
                let a = &self.ck.adts[*id as usize];
                if a.is_enum() {
                    let (tag, payload) = self.enum_layout(t);
                    match payload {
                        Some((n, unit)) => format!("{{ {tag}, [{n} x {unit}] }}"),
                        None => format!("{{ {tag} }}"),
                    }
                } else {
                    self.struct_llty(&self.ck.struct_fields(*id, args))
                }
            }
            Ty::Param(_) => "{}".into(),
        }
    }

    fn struct_llty(&self, ts: &[Ty]) -> String {
        if ts.is_empty() {
            return "{}".into();
        }
        let fs: Vec<String> = ts.iter().map(|t| self.llty(t)).collect();
        format!("{{ {} }}", fs.join(", "))
    }

    fn ret_llty(&self, t: &Ty) -> String {
        if t.is_unit() || t.is_never() {
            "void".into()
        } else {
            self.llty(t)
        }
    }

    fn abi_param(&self, t: &Ty) -> String {
        match t {
            Ty::Bool => "i1 zeroext".into(),
            _ => self.llty(t),
        }
    }

    /// (size, align) in bytes, matching LLVM's natural layout.
    pub fn layout(&self, t: &Ty) -> (u64, u64) {
        let p = (self.ptr_bits / 8) as u64;
        match t {
            Ty::Int(it) => {
                let s = (it.bits(self.ptr_bits) / 8) as u64;
                (s, s)
            }
            Ty::Float(FloatTy::F32) => (4, 4),
            Ty::Float(FloatTy::F64) => (8, 8),
            Ty::Bool => (1, 1),
            Ty::Never | Ty::Param(_) => (0, 1),
            Ty::Str | Ty::Slice(_) => (0, 1),
            Ty::Ref(inner, _) | Ty::Ptr(inner) => {
                if inner.is_unsized() {
                    (2 * p, p)
                } else {
                    (p, p)
                }
            }
            Ty::Array(e, n) => {
                let (s, a) = self.layout(e);
                (s * n, a)
            }
            Ty::Tuple(ts) => self.struct_layout(&ts.iter().map(|t| self.layout(t)).collect::<Vec<_>>()),
            Ty::Adt(id, args) => {
                if self.ck.adts[*id as usize].is_enum() {
                    let (tag, payload) = self.enum_layout(t);
                    let tag_l = match tag.as_str() {
                        "i8" => (1, 1),
                        "i16" => (2, 2),
                        "i32" => (4, 4),
                        _ => (8, 8),
                    };
                    match payload {
                        Some((n, unit)) => {
                            let u = match unit.as_str() {
                                "i8" => 1,
                                "i16" => 2,
                                "i32" => 4,
                                _ => 8,
                            };
                            self.struct_layout(&[tag_l, (n * u, u)])
                        }
                        None => tag_l,
                    }
                } else {
                    let fs = self.ck.struct_fields(*id, args);
                    self.struct_layout(&fs.iter().map(|t| self.layout(t)).collect::<Vec<_>>())
                }
            }
        }
    }

    fn struct_layout(&self, fields: &[(u64, u64)]) -> (u64, u64) {
        let mut off = 0u64;
        let mut align = 1u64;
        for &(s, a) in fields {
            off = off.div_ceil(a) * a;
            off += s;
            align = align.max(a);
        }
        (off.div_ceil(align) * align, align)
    }

    /// Tag type and payload storage `(count, unit type)` of an enum.
    fn enum_layout(&self, t: &Ty) -> (String, Option<(u64, String)>) {
        let Ty::Adt(id, args) = t else { unreachable!() };
        let a = &self.ck.adts[*id as usize];
        let (lo, hi) = a.discriminants.iter().fold((0i128, 0i128), |(lo, hi), d| (lo.min(*d), hi.max(*d)));
        let tag = if lo >= -128 && hi <= 127 {
            "i8"
        } else if lo >= -32768 && hi <= 32767 {
            "i16"
        } else if lo >= i32::MIN as i128 && hi <= i32::MAX as i128 {
            "i32"
        } else {
            "i64"
        };
        let mut size = 0;
        let mut align = 1;
        for v in self.ck.enum_variants(*id, args) {
            let (s, al) = self.struct_layout(&v.iter().map(|t| self.layout(t)).collect::<Vec<_>>());
            size = size.max(s);
            align = align.max(al);
        }
        if size == 0 {
            return (tag.into(), None);
        }
        let unit = match align {
            1 => "i8",
            2 => "i16",
            4 => "i32",
            _ => "i64",
        };
        let ua = align.min(8);
        (tag.into(), Some((size.div_ceil(ua), unit.into())))
    }

    fn variant_llty(&self, t: &Ty, idx: u32) -> String {
        let Ty::Adt(id, args) = t else { unreachable!() };
        let fields = &self.ck.enum_variants(*id, args)[idx as usize];
        self.struct_llty(fields)
    }

    fn tag_ty(&self, t: &Ty) -> String {
        self.enum_layout(t).0
    }

    fn needs_drop(&self, t: &Ty) -> bool {
        self.ck.needs_drop(t)
    }

    // --------------------------------------------------------- emission

    fn fresh(&mut self) -> String {
        self.tmp += 1;
        format!("%t{}", self.tmp)
    }

    fn new_label(&mut self, p: &str) -> String {
        self.label += 1;
        format!("{p}{}", self.label)
    }

    fn ins(&mut self, s: &str) {
        if self.terminated {
            let l = self.new_label("dead");
            let _ = writeln!(self.body, "{l}:");
            self.terminated = false;
        }
        let _ = writeln!(self.body, "  {s}");
    }

    fn term(&mut self, s: &str) {
        self.ins(s);
        self.terminated = true;
    }

    fn start(&mut self, label: &str) {
        if !self.terminated {
            let _ = writeln!(self.body, "  br label %{label}");
        }
        let _ = writeln!(self.body, "{label}:");
        self.terminated = false;
    }

    fn br(&mut self, label: &str) {
        self.term(&format!("br label %{label}"));
    }

    fn alloca(&mut self, ty: &str) -> String {
        self.tmp += 1;
        let n = format!("%a{}", self.tmp);
        let _ = writeln!(self.allocas, "  {n} = alloca {ty}");
        n
    }

    fn local_ptr(&self, l: LocalId) -> String {
        format!("%l{l}")
    }

    fn flag_ptr(&self, l: LocalId) -> String {
        format!("%f{l}")
    }

    fn local_ty(&self, l: LocalId) -> Ty {
        self.func.unwrap().locals[l as usize].ty.clone()
    }

    fn trap(&mut self) {
        self.intrinsics.insert("declare void @llvm.trap() cold noreturn nounwind".into());
        self.ins("call void @llvm.trap()");
        self.term("unreachable");
    }

    /// Branch to a trap if `cond` (i1) is false.
    fn check(&mut self, cond: &str) {
        let ok = self.new_label("ok");
        let fail = self.new_label("fail");
        self.term(&format!("br i1 {cond}, label %{ok}, label %{fail}, !prof !0"));
        let _ = writeln!(self.body, "{fail}:");
        self.terminated = false;
        self.trap();
        let _ = writeln!(self.body, "{ok}:");
        self.terminated = false;
        if !self.globals.contains("!0 = ") {
            self.globals.push_str("!0 = !{!\"branch_weights\", i32 2000, i32 1}\n");
        }
    }

    // --------------------------------------------------------- functions

    fn function(&mut self, f: &'a Func) {
        self.func = Some(f);
        self.body.clear();
        self.allocas.clear();
        self.tmp = 0;
        self.label = 0;
        self.terminated = false;
        self.scopes.clear();
        self.loops.clear();

        let mut params = Vec::new();
        for (i, &p) in f.params.iter().enumerate() {
            let t = &f.locals[p as usize].ty;
            let pty = if f.export { self.abi_param(t) } else { self.llty(t) };
            params.push(format!("{pty} %p{i}"));
        }
        for (i, l) in f.locals.iter().enumerate() {
            let _ = writeln!(self.allocas, "  %l{i} = alloca {}", self.llty(&l.ty));
            if self.needs_drop(&l.ty) {
                let _ = writeln!(self.allocas, "  %f{i} = alloca i1");
                let _ = writeln!(self.allocas, "  store i1 false, ptr %f{i}");
                self.require_glue(&l.ty);
            }
        }
        for (i, &p) in f.params.iter().enumerate() {
            let t = f.locals[p as usize].ty.clone();
            let _ = writeln!(self.body, "  store {} %p{i}, ptr %l{p}", self.llty(&t));
            if self.needs_drop(&t) {
                let _ = writeln!(self.body, "  store i1 true, ptr %f{p}");
            }
        }
        self.scopes.push(f.params.clone());
        let v = self.expr(&f.body);
        if !self.terminated {
            self.exit_scopes(0);
            if f.ret.is_unit() || f.ret.is_never() {
                self.term("ret void");
            } else {
                let t = self.llty(&f.ret);
                self.term(&format!("ret {t} {v}"));
            }
        }
        self.scopes.pop();
        let linkage = if f.export { "" } else { "internal " };
        let _ = writeln!(self.out, "define {}{} {}({}) nounwind {{", linkage, self.ret_llty(&f.ret), if f.export { format!("@{}", f.name) } else { quote(&f.name) }, params.join(", "));
        let _ = writeln!(self.out, "entry:");
        self.out.push_str(&self.allocas);
        self.out.push_str(&self.body);
        if !self.terminated {
            self.out.push_str("  unreachable\n");
        }
        let _ = writeln!(self.out, "}}\n");
    }

    // ------------------------------------------------------------- drops

    fn require_glue(&mut self, t: &Ty) {
        if self.needs_drop(t) && self.glue_done.insert(t.clone()) {
            self.glue_queue.push(t.clone());
        }
    }

    fn glue_name(&self, t: &Ty) -> String {
        quote(&format!("drop {}", self.ck.ty_mangle(t)))
    }

    /// Destroy the value at `ptr` of type `t`.
    fn drop_at(&mut self, ptr: &str, t: &Ty) {
        if !self.needs_drop(t) {
            return;
        }
        self.require_glue(t);
        let g = self.glue_name(t);
        self.ins(&format!("call void {g}(ptr {ptr})"));
    }

    fn drop_local(&mut self, l: LocalId) {
        let t = self.local_ty(l);
        if !self.needs_drop(&t) {
            return;
        }
        let f = self.flag_ptr(l);
        let c = self.fresh();
        self.ins(&format!("{c} = load i1, ptr {f}"));
        let yes = self.new_label("drop");
        let no = self.new_label("dropped");
        self.term(&format!("br i1 {c}, label %{yes}, label %{no}"));
        self.start(&yes);
        self.ins(&format!("store i1 false, ptr {f}"));
        let p = self.local_ptr(l);
        self.drop_at(&p, &t);
        self.start(&no);
    }

    /// Emit drops for scopes `depth..` (innermost first) without popping them.
    fn exit_scopes(&mut self, depth: usize) {
        let scopes: Vec<Vec<LocalId>> = self.scopes[depth..].to_vec();
        for s in scopes.iter().rev() {
            for &l in s.iter().rev() {
                self.drop_local(l);
            }
        }
    }

    fn set_flag(&mut self, l: LocalId, v: bool) {
        if self.needs_drop(&self.local_ty(l)) {
            let f = self.flag_ptr(l);
            self.ins(&format!("store i1 {v}, ptr {f}"));
        }
    }

    fn drop_glue(&mut self, t: &Ty) {
        // generated as a separate function; save per-function state
        let saved = (std::mem::take(&mut self.body), std::mem::take(&mut self.allocas), self.tmp, self.label, self.terminated);
        self.tmp = 0;
        self.label = 0;
        self.terminated = false;
        match t {
            Ty::Adt(id, args) => {
                if let Some(user) = self.ck.drop_fns.get(t) {
                    let u = quote(user);
                    self.ins(&format!("call void {u}(ptr %p)"));
                }
                let a = &self.ck.adts[*id as usize];
                if a.is_enum() {
                    let variants = self.ck.enum_variants(*id, args);
                    let ety = self.llty(t);
                    let tag_ty = self.tag_ty(t);
                    let tp = self.fresh();
                    self.ins(&format!("{tp} = getelementptr inbounds {ety}, ptr %p, i32 0, i32 0"));
                    let tag = self.fresh();
                    self.ins(&format!("{tag} = load {tag_ty}, ptr {tp}"));
                    let end = self.new_label("end");
                    for (vi, fields) in variants.iter().enumerate() {
                        if !fields.iter().any(|f| self.needs_drop(f)) {
                            continue;
                        }
                        let disc = a.discriminants[vi];
                        let c = self.fresh();
                        self.ins(&format!("{c} = icmp eq {tag_ty} {tag}, {disc}"));
                        let yes = self.new_label("v");
                        let no = self.new_label("n");
                        self.term(&format!("br i1 {c}, label %{yes}, label %{no}"));
                        self.start(&yes);
                        let vty = self.struct_llty(fields);
                        let pp = self.fresh();
                        self.ins(&format!("{pp} = getelementptr inbounds {ety}, ptr %p, i32 0, i32 1"));
                        for (fi, ft) in fields.iter().enumerate() {
                            if self.needs_drop(ft) {
                                let fp = self.fresh();
                                self.ins(&format!("{fp} = getelementptr inbounds {vty}, ptr {pp}, i32 0, i32 {fi}"));
                                self.drop_at(&fp, ft);
                            }
                        }
                        self.br(&end);
                        self.start(&no);
                    }
                    self.start(&end);
                } else {
                    let fields = self.ck.struct_fields(*id, args);
                    self.drop_fields(t, &fields);
                }
            }
            Ty::Tuple(ts) => {
                let ts = ts.clone();
                self.drop_fields(t, &ts);
            }
            Ty::Array(e, n) => {
                let aty = self.llty(t);
                let us = self.usize_ty();
                let i = self.alloca(&us);
                self.ins(&format!("store {us} 0, ptr {i}"));
                let head = self.new_label("head");
                let bodyl = self.new_label("body");
                let end = self.new_label("end");
                self.start(&head);
                let iv = self.fresh();
                self.ins(&format!("{iv} = load {us}, ptr {i}"));
                let c = self.fresh();
                self.ins(&format!("{c} = icmp ult {us} {iv}, {n}"));
                self.term(&format!("br i1 {c}, label %{bodyl}, label %{end}"));
                self.start(&bodyl);
                let ep = self.fresh();
                self.ins(&format!("{ep} = getelementptr inbounds {aty}, ptr %p, {us} 0, {us} {iv}"));
                self.drop_at(&ep, e);
                let nx = self.fresh();
                self.ins(&format!("{nx} = add {us} {iv}, 1"));
                self.ins(&format!("store {us} {nx}, ptr {i}"));
                self.br(&head);
                self.start(&end);
            }
            _ => {}
        }
        if !self.terminated {
            self.term("ret void");
        }
        let name = self.glue_name(t);
        let _ = writeln!(self.out, "define internal void {name}(ptr %p) nounwind {{\nentry:");
        self.out.push_str(&self.allocas);
        self.out.push_str(&self.body);
        let _ = writeln!(self.out, "}}\n");
        (self.body, self.allocas, self.tmp, self.label, self.terminated) = saved;
    }

    fn drop_fields(&mut self, t: &Ty, fields: &[Ty]) {
        let sty = self.llty(t);
        for (i, ft) in fields.iter().enumerate() {
            if self.needs_drop(ft) {
                let fp = self.fresh();
                self.ins(&format!("{fp} = getelementptr inbounds {sty}, ptr %p, i32 0, i32 {i}"));
                self.drop_at(&fp, ft);
            }
        }
    }

    // ------------------------------------------------------------ places

    fn place_ty(&self, p: &Place) -> Ty {
        match p {
            Place::Local(l) => self.local_ty(*l),
            Place::Static(..) => unreachable!("static type requested without context"),
            Place::Field(b, i) => match self.place_ty_ctx(b) {
                Ty::Adt(id, args) => self.ck.struct_fields(id, &args)[*i as usize].clone(),
                Ty::Tuple(ts) => ts[*i as usize].clone(),
                _ => unreachable!(),
            },
            Place::Index(b, _) => match self.place_ty_ctx(b) {
                Ty::Array(e, _) | Ty::Slice(e) => *e,
                _ => unreachable!(),
            },
            Place::Deref(e) => match &e.ty {
                Ty::Ref(t, _) | Ty::Ptr(t) => (**t).clone(),
                _ => unreachable!(),
            },
        }
    }

    fn place_ty_ctx(&self, p: &Place) -> Ty {
        match p {
            Place::Static(name, _) => self.static_tys().get(name).cloned().expect("static type"),
            _ => self.place_ty(p),
        }
    }

    fn static_tys(&self) -> HashMap<String, Ty> {
        let mut m = HashMap::new();
        for s in &self.ck.statics {
            if let Some(t) = &s.resolved {
                m.insert(s.symbol.clone(), t.clone());
            }
        }
        m
    }

    fn place_ptr(&mut self, p: &Place) -> PlacePtr {
        match p {
            Place::Local(l) => PlacePtr::Thin(self.local_ptr(*l)),
            Place::Static(name, _) => PlacePtr::Thin(quote(name)),
            Place::Field(b, i) => {
                let bt = self.place_ty_ctx(b);
                let PlacePtr::Thin(bp) = self.place_ptr(b) else { unreachable!() };
                let r = self.fresh();
                let sty = self.llty(&bt);
                self.ins(&format!("{r} = getelementptr inbounds {sty}, ptr {bp}, i32 0, i32 {i}"));
                PlacePtr::Thin(r)
            }
            Place::Index(b, idx) => {
                let bt = self.place_ty_ctx(b);
                let base = self.place_ptr(b);
                let iv = self.expr(idx);
                let us = self.usize_ty();
                match (&bt, base) {
                    (Ty::Array(e, n), PlacePtr::Thin(bp)) => {
                        let c = self.fresh();
                        self.ins(&format!("{c} = icmp ult {us} {iv}, {n}"));
                        self.check(&c);
                        let r = self.fresh();
                        let aty = self.llty(&bt);
                        let _ = e;
                        self.ins(&format!("{r} = getelementptr inbounds {aty}, ptr {bp}, {us} 0, {us} {iv}"));
                        PlacePtr::Thin(r)
                    }
                    (Ty::Slice(e), PlacePtr::Fat(fv)) => {
                        let fty = format!("{{ ptr, {us} }}");
                        let data = self.fresh();
                        self.ins(&format!("{data} = extractvalue {fty} {fv}, 0"));
                        let len = self.fresh();
                        self.ins(&format!("{len} = extractvalue {fty} {fv}, 1"));
                        let c = self.fresh();
                        self.ins(&format!("{c} = icmp ult {us} {iv}, {len}"));
                        self.check(&c);
                        let r = self.fresh();
                        let ety = self.llty(e);
                        self.ins(&format!("{r} = getelementptr inbounds {ety}, ptr {data}, {us} {iv}"));
                        PlacePtr::Thin(r)
                    }
                    _ => unreachable!("bad index base"),
                }
            }
            Place::Deref(e) => {
                let v = self.expr(e);
                if e.ty.is_fat_ref() {
                    PlacePtr::Fat(v)
                } else {
                    PlacePtr::Thin(v)
                }
            }
        }
    }

    fn thin(&mut self, p: &Place) -> String {
        match self.place_ptr(p) {
            PlacePtr::Thin(s) => s,
            PlacePtr::Fat(_) => unreachable!("unsized place used by value"),
        }
    }

    /// Moving out of `x.a.b` consumes `x`: the sibling fields along the path
    /// are destroyed immediately and `x`'s drop flag is cleared.
    fn consume_path(&mut self, p: &Place) {
        match p {
            Place::Local(l) => self.set_flag(*l, false),
            Place::Field(b, i) => {
                let bt = self.place_ty_ctx(b);
                let fields = match &bt {
                    Ty::Adt(id, args) => self.ck.struct_fields(*id, args),
                    Ty::Tuple(ts) => ts.clone(),
                    _ => Vec::new(),
                };
                if fields.iter().enumerate().any(|(j, f)| j as u32 != *i && self.needs_drop(f)) {
                    let bp = self.thin(b);
                    let sty = self.llty(&bt);
                    for (j, f) in fields.iter().enumerate() {
                        if j as u32 != *i && self.needs_drop(f) {
                            let fp = self.fresh();
                            self.ins(&format!("{fp} = getelementptr inbounds {sty}, ptr {bp}, i32 0, i32 {j}"));
                            self.drop_at(&fp, f);
                        }
                    }
                }
                self.consume_path(b);
            }
            _ => {}
        }
    }

    // ------------------------------------------------------- expressions

    fn unit(&self) -> String {
        "zeroinitializer".into()
    }

    fn expr(&mut self, e: &Expr) -> String {
        match &e.kind {
            K::Int(v) => match &e.ty {
                Ty::Float(f) => float_lit(*v as f64, *f),
                _ => v.to_string(),
            },
            K::Float(v) => match &e.ty {
                Ty::Float(f) => float_lit(*v, *f),
                _ => float_lit(*v, FloatTy::F64),
            },
            K::Bool(b) => b.to_string(),
            K::Str(s) => {
                let g = self.string(s);
                format!("{{ ptr {g}, {} {} }}", self.usize_ty(), s.len())
            }
            K::Unit => self.unit(),
            K::Use(p, kind) => {
                let ty = e.ty.clone();
                let ptr = self.thin(p);
                let r = self.fresh();
                let lt = self.llty(&ty);
                self.ins(&format!("{r} = load {lt}, ptr {ptr}"));
                if *kind == UseKind::Move && self.needs_drop(&ty) {
                    self.consume_path(p);
                } else if *kind == UseKind::Move {
                    // still consumes siblings that need dropping
                    if let Place::Field(..) = p {
                        self.consume_path(p);
                    }
                }
                r
            }
            K::Borrow(p, _) => match self.place_ptr(p) {
                PlacePtr::Thin(s) => s,
                PlacePtr::Fat(v) => v,
            },
            K::Unary(op, a) => {
                let v = self.expr(a);
                let t = self.llty(&a.ty);
                let r = self.fresh();
                match (op, &a.ty) {
                    (UnOp::Neg, Ty::Float(_)) => self.ins(&format!("{r} = fneg {t} {v}")),
                    (UnOp::Neg, _) => self.ins(&format!("{r} = sub {t} 0, {v}")),
                    (UnOp::Not, Ty::Bool) => self.ins(&format!("{r} = xor i1 {v}, true")),
                    (UnOp::Not, _) => self.ins(&format!("{r} = xor {t} {v}, -1")),
                }
                r
            }
            K::Binary(op, a, b) => self.binary(*op, a, b, &e.ty),
            K::Cast(a, to) => self.cast(a, to),
            K::ArrayToSlice(a) => {
                let v = self.expr(a);
                let n = match &a.ty {
                    Ty::Ref(inner, _) => match &**inner {
                        Ty::Array(_, n) => *n,
                        _ => 0,
                    },
                    _ => 0,
                };
                let us = self.usize_ty();
                let fty = format!("{{ ptr, {us} }}");
                let r1 = self.fresh();
                self.ins(&format!("{r1} = insertvalue {fty} poison, ptr {v}, 0"));
                let r2 = self.fresh();
                self.ins(&format!("{r2} = insertvalue {fty} {r1}, {us} {n}, 1"));
                r2
            }
            K::Call(name, args) => {
                let mut vals = Vec::new();
                for a in args {
                    let v = self.expr(a);
                    vals.push(format!("{} {}", self.llty(&a.ty), v));
                }
                let callee = if self.is_extern_name(name) { format!("@{name}") } else { quote(name) };
                let rt = self.ret_llty(&e.ty);
                let variadic = self.extern_sig(name);
                let call_ty = match variadic {
                    Some(sig) => sig,
                    None => rt.clone(),
                };
                if rt == "void" {
                    self.ins(&format!("call {call_ty} {callee}({})", vals.join(", ")));
                    if e.ty.is_never() {
                        self.term("unreachable");
                        return "poison".into();
                    }
                    self.unit()
                } else {
                    let r = self.fresh();
                    self.ins(&format!("{r} = call {call_ty} {callee}({})", vals.join(", ")));
                    r
                }
            }
            K::Intrinsic(i, args) => self.intrinsic(i, args, &e.ty),
            K::Struct(fields) | K::Tuple(fields) => {
                let lt = self.llty(&e.ty);
                if fields.is_empty() {
                    return "zeroinitializer".into();
                }
                let mut cur = "poison".to_string();
                for (i, f) in fields.iter().enumerate() {
                    let v = self.expr(f);
                    let ft = self.llty(&f.ty);
                    let r = self.fresh();
                    self.ins(&format!("{r} = insertvalue {lt} {cur}, {ft} {v}, {i}"));
                    cur = r;
                }
                cur
            }
            K::Array(items) => {
                let lt = self.llty(&e.ty);
                if items.is_empty() {
                    return "zeroinitializer".into();
                }
                let mut cur = "poison".to_string();
                for (i, f) in items.iter().enumerate() {
                    let v = self.expr(f);
                    let ft = self.llty(&f.ty);
                    let r = self.fresh();
                    self.ins(&format!("{r} = insertvalue {lt} {cur}, {ft} {v}, {i}"));
                    cur = r;
                }
                cur
            }
            K::ArrayRepeat(item, n) => {
                let v = self.expr(item);
                let lt = self.llty(&e.ty);
                if *n == 0 {
                    return "zeroinitializer".into();
                }
                if v == "0" || v == "false" || v == "zeroinitializer" || v == "0x0000000000000000" {
                    return "zeroinitializer".into();
                }
                let et = self.llty(&item.ty);
                if *n <= 16 {
                    let mut cur = "poison".to_string();
                    for i in 0..*n {
                        let r = self.fresh();
                        self.ins(&format!("{r} = insertvalue {lt} {cur}, {et} {v}, {i}"));
                        cur = r;
                    }
                    return cur;
                }
                // fill loop
                let arr = self.alloca(&lt);
                let us = self.usize_ty();
                let i = self.alloca(&us);
                self.ins(&format!("store {us} 0, ptr {i}"));
                let head = self.new_label("fill");
                let body = self.new_label("fillb");
                let end = self.new_label("filled");
                self.start(&head);
                let iv = self.fresh();
                self.ins(&format!("{iv} = load {us}, ptr {i}"));
                let c = self.fresh();
                self.ins(&format!("{c} = icmp ult {us} {iv}, {n}"));
                self.term(&format!("br i1 {c}, label %{body}, label %{end}"));
                self.start(&body);
                let ep = self.fresh();
                self.ins(&format!("{ep} = getelementptr inbounds {lt}, ptr {arr}, {us} 0, {us} {iv}"));
                self.ins(&format!("store {et} {v}, ptr {ep}"));
                let nx = self.fresh();
                self.ins(&format!("{nx} = add {us} {iv}, 1"));
                self.ins(&format!("store {us} {nx}, ptr {i}"));
                self.br(&head);
                self.start(&end);
                let r = self.fresh();
                self.ins(&format!("{r} = load {lt}, ptr {arr}"));
                r
            }
            K::Variant(idx, fields) => {
                let lt = self.llty(&e.ty);
                let vals: Vec<(String, Ty)> = fields.iter().map(|f| (self.expr(f), f.ty.clone())).collect();
                let tmp = self.alloca(&lt);
                let Ty::Adt(id, _) = &e.ty else { unreachable!() };
                let disc = self.ck.adts[*id as usize].discriminants[*idx as usize];
                let tag_ty = self.tag_ty(&e.ty);
                let tp = self.fresh();
                self.ins(&format!("{tp} = getelementptr inbounds {lt}, ptr {tmp}, i32 0, i32 0"));
                self.ins(&format!("store {tag_ty} {disc}, ptr {tp}"));
                if !vals.is_empty() {
                    let vty = self.variant_llty(&e.ty, *idx);
                    let pp = self.fresh();
                    self.ins(&format!("{pp} = getelementptr inbounds {lt}, ptr {tmp}, i32 0, i32 1"));
                    for (i, (v, t)) in vals.iter().enumerate() {
                        let fp = self.fresh();
                        self.ins(&format!("{fp} = getelementptr inbounds {vty}, ptr {pp}, i32 0, i32 {i}"));
                        let ft = self.llty(t);
                        self.ins(&format!("store {ft} {v}, ptr {fp}"));
                    }
                }
                let r = self.fresh();
                self.ins(&format!("{r} = load {lt}, ptr {tmp}"));
                r
            }
            K::Assign(p, v) => {
                let val = self.expr(v);
                let ty = v.ty.clone();
                let lt = self.llty(&ty);
                if let Place::Local(l) = p {
                    if self.needs_drop(&ty) {
                        self.drop_local(*l);
                    }
                    let ptr = self.local_ptr(*l);
                    self.ins(&format!("store {lt} {val}, ptr {ptr}"));
                    self.set_flag(*l, true);
                } else {
                    let ptr = self.thin(p);
                    if self.needs_drop(&ty) {
                        self.drop_at(&ptr, &ty);
                    }
                    self.ins(&format!("store {lt} {val}, ptr {ptr}"));
                }
                self.unit()
            }
            K::CompoundAssign(op, p, v) => {
                let val = self.expr(v);
                let ptr = self.thin(p);
                let ty = self.place_ty_ctx(p);
                let lt = self.llty(&ty);
                let cur = self.fresh();
                self.ins(&format!("{cur} = load {lt}, ptr {ptr}"));
                let r = self.arith(*op, &cur, &val, &ty, &v.ty, false);
                self.ins(&format!("store {lt} {r}, ptr {ptr}"));
                self.unit()
            }
            K::Block(b) => self.block(b, &e.ty),
            K::If(c, t, els) => {
                let cv = self.expr(c);
                let then_l = self.new_label("then");
                let else_l = self.new_label("else");
                let end_l = self.new_label("endif");
                let has_val = !(e.ty.is_unit() || e.ty.is_never());
                let slot = if has_val { Some(self.alloca(&self.llty(&e.ty))) } else { None };
                self.term(&format!("br i1 {cv}, label %{then_l}, label %{else_l}"));
                self.start(&then_l);
                let tv = self.expr(t);
                if let (Some(s), false) = (&slot, self.terminated) {
                    let lt = self.llty(&e.ty);
                    self.ins(&format!("store {lt} {tv}, ptr {s}"));
                }
                if !self.terminated {
                    self.br(&end_l);
                }
                self.start(&else_l);
                if let Some(x) = els {
                    let ev = self.expr(x);
                    if let (Some(s), false) = (&slot, self.terminated) {
                        let lt = self.llty(&e.ty);
                        self.ins(&format!("store {lt} {ev}, ptr {s}"));
                    }
                }
                if !self.terminated {
                    self.br(&end_l);
                }
                self.start(&end_l);
                match slot {
                    Some(s) => {
                        let r = self.fresh();
                        let lt = self.llty(&e.ty);
                        self.ins(&format!("{r} = load {lt}, ptr {s}"));
                        r
                    }
                    None => self.unit(),
                }
            }
            K::Loop(body, id) => {
                let head = self.new_label("loop");
                let exit = self.new_label("endloop");
                let has_val = !(e.ty.is_unit() || e.ty.is_never());
                let slot = if has_val { Some(self.alloca(&self.llty(&e.ty))) } else { None };
                self.loops.push(LoopCg { id: *id, head: head.clone(), exit: exit.clone(), depth: self.scopes.len(), slot: slot.clone() });
                self.start(&head);
                self.expr(body);
                if !self.terminated {
                    self.br(&head);
                }
                self.loops.pop();
                let _ = writeln!(self.body, "{exit}:");
                self.terminated = false;
                if e.ty.is_never() {
                    self.term("unreachable");
                    return "poison".into();
                }
                match slot {
                    Some(s) => {
                        let r = self.fresh();
                        let lt = self.llty(&e.ty);
                        self.ins(&format!("{r} = load {lt}, ptr {s}"));
                        r
                    }
                    None => self.unit(),
                }
            }
            K::Break(id, v) => {
                let val = v.as_ref().map(|v| (self.expr(v), v.ty.clone()));
                let lp = self.loops.iter().rev().find(|l| l.id == *id).expect("loop");
                let (exit, depth, slot) = (lp.exit.clone(), lp.depth, lp.slot.clone());
                if let (Some((v, t)), Some(s)) = (val, slot) {
                    if !self.terminated {
                        let lt = self.llty(&t);
                        self.ins(&format!("store {lt} {v}, ptr {s}"));
                    }
                }
                if !self.terminated {
                    self.exit_scopes(depth);
                    self.br(&exit);
                }
                "poison".into()
            }
            K::Continue(id) => {
                let lp = self.loops.iter().rev().find(|l| l.id == *id).expect("loop");
                let (head, depth) = (lp.head.clone(), lp.depth);
                self.exit_scopes(depth);
                self.br(&head);
                "poison".into()
            }
            K::Return(v) => {
                let val = v.as_ref().map(|v| self.expr(v));
                if self.terminated {
                    return "poison".into();
                }
                self.exit_scopes(0);
                let rt = self.func.unwrap().ret.clone();
                match val {
                    Some(v) if !rt.is_unit() && !rt.is_never() => {
                        let lt = self.llty(&rt);
                        self.term(&format!("ret {lt} {v}"));
                    }
                    _ => self.term("ret void"),
                }
                "poison".into()
            }
            K::Match(p, arms) => self.match_expr(p, arms, &e.ty),
            K::Is(p, pat) => {
                let ty = self.place_ty_ctx(p);
                let ptr = self.thin(p);
                let slot = self.alloca("i1");
                self.ins(&format!("store i1 false, ptr {slot}"));
                let end = self.new_label("isend");
                self.pat_test(pat, &ptr, &ty, &end);
                self.ins(&format!("store i1 true, ptr {slot}"));
                self.br(&end);
                self.start(&end);
                let r = self.fresh();
                self.ins(&format!("{r} = load i1, ptr {slot}"));
                r
            }
            K::Drop(p) => {
                if let Place::Local(l) = p {
                    self.drop_local(*l);
                }
                self.unit()
            }
        }
    }

    fn is_extern_name(&self, name: &str) -> bool {
        self.externs.contains_key(name)
    }

    /// For variadic externs the call needs the full function type.
    fn extern_sig(&self, name: &str) -> Option<String> {
        let (params, ret, variadic) = self.externs.get(name)?;
        if !*variadic {
            return None;
        }
        let ps: Vec<String> = params.iter().map(|t| self.llty(t)).collect();
        let mut s = ps.join(", ");
        if !s.is_empty() {
            s.push_str(", ");
        }
        s.push_str("...");
        Some(format!("{} ({})", self.ret_llty(ret), s))
    }

    fn string(&mut self, s: &[u8]) -> String {
        if let Some(g) = self.strings.get(s) {
            return g.clone();
        }
        let name = format!("@.str.{}", self.strings.len());
        let mut lit = String::new();
        for &b in s {
            if (0x20..0x7f).contains(&b) && b != b'"' && b != b'\\' {
                lit.push(b as char);
            } else {
                let _ = write!(lit, "\\{b:02X}");
            }
        }
        let _ = writeln!(self.globals, "{name} = private unnamed_addr constant [{} x i8] c\"{}\"", s.len(), lit);
        self.strings.insert(s.to_vec(), name.clone());
        name
    }

    fn block(&mut self, b: &xir::Block, ty: &Ty) -> String {
        self.scopes.push(b.scope.clone());
        for s in &b.stmts {
            match s {
                Stmt::Let(l, v) => {
                    let val = self.expr(v);
                    if !self.terminated {
                        let lt = self.llty(&v.ty);
                        let p = self.local_ptr(*l);
                        self.ins(&format!("store {lt} {val}, ptr {p}"));
                        self.set_flag(*l, true);
                    }
                }
                Stmt::LetPat(pat, v) => {
                    let val = self.expr(v);
                    if !self.terminated {
                        let lt = self.llty(&v.ty);
                        let tmp = self.alloca(&lt);
                        self.ins(&format!("store {lt} {val}, ptr {tmp}"));
                        let vt = v.ty.clone();
                        self.pat_bind(pat, &tmp, &vt);
                        self.drop_unbound(pat, &tmp, &vt);
                    }
                }
                Stmt::Expr(x) => {
                    let v = self.expr(x);
                    if !self.terminated && self.needs_drop(&x.ty) && !matches!(x.kind, K::Use(_, UseKind::Copy)) {
                        let lt = self.llty(&x.ty);
                        let tmp = self.alloca(&lt);
                        self.ins(&format!("store {lt} {v}, ptr {tmp}"));
                        let t = x.ty.clone();
                        self.drop_at(&tmp, &t);
                    }
                }
            }
        }
        let v = match &b.tail {
            Some(t) => self.expr(t),
            None => self.unit(),
        };
        let _ = ty;
        if !self.terminated {
            let depth = self.scopes.len() - 1;
            self.exit_scopes(depth);
        }
        self.scopes.pop();
        v
    }

    // --------------------------------------------------------- operators

    fn binary(&mut self, op: BinOp, a: &Expr, b: &Expr, ty: &Ty) -> String {
        if matches!(op, BinOp::And | BinOp::Or) {
            let slot = self.alloca("i1");
            let l = self.expr(a);
            self.ins(&format!("store i1 {l}, ptr {slot}"));
            let rhs = self.new_label("rhs");
            let end = self.new_label("sc");
            if op == BinOp::And {
                self.term(&format!("br i1 {l}, label %{rhs}, label %{end}"));
            } else {
                self.term(&format!("br i1 {l}, label %{end}, label %{rhs}"));
            }
            self.start(&rhs);
            let r = self.expr(b);
            if !self.terminated {
                self.ins(&format!("store i1 {r}, ptr {slot}"));
            }
            self.start(&end);
            let res = self.fresh();
            self.ins(&format!("{res} = load i1, ptr {slot}"));
            return res;
        }
        let l = self.expr(a);
        let r = self.expr(b);
        if op.is_comparison() {
            return self.compare(op, &l, &r, &a.ty);
        }
        self.arith(op, &l, &r, ty, &b.ty, matches!(b.kind, K::Int(n) if n != 0 && n != -1))
    }

    fn compare(&mut self, op: BinOp, l: &str, r: &str, ty: &Ty) -> String {
        let res = self.fresh();
        match ty {
            Ty::Float(_) => {
                let pred = match op {
                    BinOp::Eq => "oeq",
                    BinOp::Ne => "une",
                    BinOp::Lt => "olt",
                    BinOp::Le => "ole",
                    BinOp::Gt => "ogt",
                    _ => "oge",
                };
                let t = self.llty(ty);
                self.ins(&format!("{res} = fcmp {pred} {t} {l}, {r}"));
            }
            Ty::Adt(..) => {
                // fieldless enums: compare tags
                let lt = self.llty(ty);
                let tt = self.tag_ty(ty);
                let a = self.fresh();
                self.ins(&format!("{a} = extractvalue {lt} {l}, 0"));
                let b = self.fresh();
                self.ins(&format!("{b} = extractvalue {lt} {r}, 0"));
                let pred = if op == BinOp::Eq { "eq" } else { "ne" };
                self.ins(&format!("{res} = icmp {pred} {tt} {a}, {b}"));
            }
            _ => {
                let signed = matches!(ty, Ty::Int(it) if it.signed());
                let pred = match op {
                    BinOp::Eq => "eq",
                    BinOp::Ne => "ne",
                    BinOp::Lt => if signed { "slt" } else { "ult" },
                    BinOp::Le => if signed { "sle" } else { "ule" },
                    BinOp::Gt => if signed { "sgt" } else { "ugt" },
                    _ => if signed { "sge" } else { "uge" },
                };
                let t = self.llty(ty);
                self.ins(&format!("{res} = icmp {pred} {t} {l}, {r}"));
            }
        }
        res
    }

    /// Integer arithmetic wraps (two's complement); division by zero and
    /// `MIN / -1` trap; shift amounts are masked to the bit width.
    fn arith(&mut self, op: BinOp, l: &str, r: &str, ty: &Ty, rty: &Ty, divisor_safe: bool) -> String {
        let t = self.llty(ty);
        let res = self.fresh();
        match ty {
            Ty::Float(_) => {
                let ins = match op {
                    BinOp::Add => "fadd",
                    BinOp::Sub => "fsub",
                    BinOp::Mul => "fmul",
                    BinOp::Div => "fdiv",
                    _ => "frem",
                };
                self.ins(&format!("{res} = {ins} {t} {l}, {r}"));
            }
            Ty::Ptr(inner) => {
                let us = self.usize_ty();
                let rt = self.llty(rty);
                let off = if rt != us {
                    let c = self.fresh();
                    let signed = matches!(rty, Ty::Int(it) if it.signed());
                    let (rb, ub) = (rty_bits(rty, self.ptr_bits), self.ptr_bits);
                    let ins = if rb > ub { "trunc" } else if signed { "sext" } else { "zext" };
                    self.ins(&format!("{c} = {ins} {rt} {r} to {us}"));
                    c
                } else {
                    r.to_string()
                };
                let off = if op == BinOp::Sub {
                    let n = self.fresh();
                    self.ins(&format!("{n} = sub {us} 0, {off}"));
                    n
                } else {
                    off
                };
                let et = if inner.is_unsized() || matches!(**inner, Ty::Tuple(ref v) if v.is_empty()) { "i8".to_string() } else { self.llty(inner) };
                self.ins(&format!("{res} = getelementptr {et}, ptr {l}, {us} {off}"));
            }
            Ty::Bool => {
                let ins = match op {
                    BinOp::BitAnd => "and",
                    BinOp::BitOr => "or",
                    _ => "xor",
                };
                self.ins(&format!("{res} = {ins} i1 {l}, {r}"));
            }
            Ty::Int(it) => {
                let signed = it.signed();
                let bits = it.bits(self.ptr_bits);
                match op {
                    BinOp::Shl | BinOp::Shr => {
                        let rt = self.llty(rty);
                        let rb = rty_bits(rty, self.ptr_bits);
                        let amt = if rb != bits {
                            let c = self.fresh();
                            let ins = if rb > bits { "trunc" } else { "zext" };
                            self.ins(&format!("{c} = {ins} {rt} {r} to {t}"));
                            c
                        } else {
                            r.to_string()
                        };
                        let m = self.fresh();
                        self.ins(&format!("{m} = and {t} {amt}, {}", bits - 1));
                        let ins = match (op, signed) {
                            (BinOp::Shl, _) => "shl",
                            (_, true) => "ashr",
                            _ => "lshr",
                        };
                        self.ins(&format!("{res} = {ins} {t} {l}, {m}"));
                    }
                    BinOp::Div | BinOp::Rem => {
                        if !divisor_safe {
                            let nz = self.fresh();
                            self.ins(&format!("{nz} = icmp ne {t} {r}, 0"));
                            self.check(&nz);
                            if signed {
                                let min = -(1i128 << (bits - 1));
                                let a = self.fresh();
                                self.ins(&format!("{a} = icmp ne {t} {l}, {min}"));
                                let b = self.fresh();
                                self.ins(&format!("{b} = icmp ne {t} {r}, -1"));
                                let c = self.fresh();
                                self.ins(&format!("{c} = or i1 {a}, {b}"));
                                self.check(&c);
                            }
                        }
                        let ins = match (op, signed) {
                            (BinOp::Div, true) => "sdiv",
                            (BinOp::Div, false) => "udiv",
                            (_, true) => "srem",
                            _ => "urem",
                        };
                        self.ins(&format!("{res} = {ins} {t} {l}, {r}"));
                    }
                    _ => {
                        let ins = match op {
                            BinOp::Add => "add",
                            BinOp::Sub => "sub",
                            BinOp::Mul => "mul",
                            BinOp::BitAnd => "and",
                            BinOp::BitOr => "or",
                            _ => "xor",
                        };
                        self.ins(&format!("{res} = {ins} {t} {l}, {r}"));
                    }
                }
            }
            _ => unreachable!("arith on {:?}", ty),
        }
        res
    }

    fn cast(&mut self, a: &Expr, to: &Ty) -> String {
        let v = self.expr(a);
        let from = a.ty.clone();
        if from == *to {
            return v;
        }
        let ft = self.llty(&from);
        let tt = self.llty(to);
        let r = self.fresh();
        match (&from, to) {
            (Ty::Int(fi), Ty::Int(ti)) => {
                let (fb, tb) = (fi.bits(self.ptr_bits), ti.bits(self.ptr_bits));
                if fb == tb {
                    return v;
                }
                let ins = if fb > tb { "trunc" } else if fi.signed() { "sext" } else { "zext" };
                self.ins(&format!("{r} = {ins} {ft} {v} to {tt}"));
            }
            (Ty::Bool, Ty::Int(_)) => self.ins(&format!("{r} = zext i1 {v} to {tt}")),
            (Ty::Int(fi), Ty::Float(_)) => {
                let ins = if fi.signed() { "sitofp" } else { "uitofp" };
                self.ins(&format!("{r} = {ins} {ft} {v} to {tt}"));
            }
            (Ty::Float(_), Ty::Int(ti)) => {
                let name = format!("llvm.fpto{}i.sat.{}.{}", if ti.signed() { "s" } else { "u" }, tt, if ft == "float" { "f32" } else { "f64" });
                self.intrinsics.insert(format!("declare {tt} @{name}({ft}) nounwind readnone"));
                self.ins(&format!("{r} = call {tt} @{name}({ft} {v})"));
            }
            (Ty::Float(FloatTy::F32), Ty::Float(FloatTy::F64)) => self.ins(&format!("{r} = fpext float {v} to double")),
            (Ty::Float(FloatTy::F64), Ty::Float(FloatTy::F32)) => self.ins(&format!("{r} = fptrunc double {v} to float")),
            (Ty::Ptr(_) | Ty::Ref(..), Ty::Ptr(_)) => return v,
            (Ty::Ptr(_), Ty::Int(_)) => self.ins(&format!("{r} = ptrtoint ptr {v} to {tt}")),
            (Ty::Int(_), Ty::Ptr(_)) => self.ins(&format!("{r} = inttoptr {ft} {v} to ptr")),
            (Ty::Adt(..), Ty::Int(ti)) => {
                let tag_ty = self.tag_ty(&from);
                let t = self.fresh();
                self.ins(&format!("{t} = extractvalue {ft} {v}, 0"));
                let tb: u32 = tag_ty[1..].parse().unwrap();
                let bits = ti.bits(self.ptr_bits);
                if tb == bits {
                    return t;
                }
                let ins = if tb > bits { "trunc" } else { "sext" };
                self.ins(&format!("{r} = {ins} {tag_ty} {t} to {tt}"));
            }
            _ => return v,
        }
        r
    }

    fn intrinsic(&mut self, i: &Intrinsic, args: &[Expr], ty: &Ty) -> String {
        match i {
            Intrinsic::SizeOf(t) => self.layout(t).0.to_string(),
            Intrinsic::AlignOf(t) => self.layout(t).1.to_string(),
            Intrinsic::Trap => {
                self.trap();
                "poison".into()
            }
            Intrinsic::Asm(s) => {
                let esc = s.replace('\\', "\\5C").replace('"', "\\22").replace('\n', "\\0A");
                self.ins(&format!("call void asm sideeffect \"{esc}\", \"~{{memory}}\"()"));
                self.unit()
            }
            Intrinsic::MakeFat => {
                let p = self.expr(&args[0]);
                let n = self.expr(&args[1]);
                let lt = self.llty(ty);
                let us = self.usize_ty();
                let r1 = self.fresh();
                self.ins(&format!("{r1} = insertvalue {lt} poison, ptr {p}, 0"));
                let r2 = self.fresh();
                self.ins(&format!("{r2} = insertvalue {lt} {r1}, {us} {n}, 1"));
                r2
            }
            Intrinsic::Len => {
                let v = self.expr(&args[0]);
                if let Ty::Ref(inner, _) = &args[0].ty {
                    if let Ty::Array(_, n) = &**inner {
                        return n.to_string();
                    }
                }
                let lt = self.llty(&args[0].ty);
                let r = self.fresh();
                self.ins(&format!("{r} = extractvalue {lt} {v}, 1"));
                r
            }
            Intrinsic::PtrRead => {
                let p = self.expr(&args[0]);
                let lt = self.llty(ty);
                let r = self.fresh();
                self.ins(&format!("{r} = load {lt}, ptr {p}"));
                r
            }
            Intrinsic::PtrWrite => {
                let p = self.expr(&args[0]);
                let v = self.expr(&args[1]);
                let lt = self.llty(&args[1].ty);
                self.ins(&format!("store {lt} {v}, ptr {p}"));
                self.unit()
            }
            Intrinsic::DropInPlace(t) => {
                let p = self.expr(&args[0]);
                let t = t.clone();
                self.drop_at(&p, &t);
                self.unit()
            }
            Intrinsic::Forget => {
                self.expr(&args[0]);
                self.unit()
            }
            Intrinsic::DataPtr => {
                let v = self.expr(&args[0]);
                let lt = self.llty(&args[0].ty);
                let r = self.fresh();
                self.ins(&format!("{r} = extractvalue {lt} {v}, 0"));
                r
            }
        }
    }

    // ---------------------------------------------------------- patterns

    fn match_expr(&mut self, p: &Place, arms: &[xir::Arm], ty: &Ty) -> String {
        let sty = self.place_ty_ctx(p);
        let ptr = self.thin(p);
        let has_val = !(ty.is_unit() || ty.is_never());
        let slot = if has_val { Some(self.alloca(&self.llty(ty))) } else { None };
        let end = self.new_label("endmatch");
        for arm in arms {
            let next = self.new_label("arm");
            self.pat_test(&arm.pat, &ptr, &sty, &next);
            let moves = self.pat_moves(&arm.pat);
            self.pat_bind(&arm.pat, &ptr, &sty);
            if moves {
                // the scrutinee is consumed by this arm
                if let Place::Local(l) = p {
                    self.set_flag(*l, false);
                }
                self.drop_unbound(&arm.pat, &ptr, &sty);
            }
            if let Some(g) = &arm.guard {
                let gv = self.expr(g);
                let body = self.new_label("guarded");
                self.term(&format!("br i1 {gv}, label %{body}, label %{next}"));
                self.start(&body);
            }
            let v = self.expr(&arm.body);
            if let (Some(s), false) = (&slot, self.terminated) {
                let lt = self.llty(ty);
                self.ins(&format!("store {lt} {v}, ptr {s}"));
            }
            if !self.terminated {
                self.br(&end);
            }
            self.start(&next);
        }
        self.term("unreachable");
        let _ = writeln!(self.body, "{end}:");
        self.terminated = false;
        if ty.is_never() {
            self.term("unreachable");
            return "poison".into();
        }
        match slot {
            Some(s) => {
                let r = self.fresh();
                let lt = self.llty(ty);
                self.ins(&format!("{r} = load {lt}, ptr {s}"));
                r
            }
            None => self.unit(),
        }
    }

    fn pat_moves(&self, p: &Pat) -> bool {
        match p {
            Pat::Bind(id, BindMode::Value) => !self.ck.is_copy(&self.local_ty(*id)),
            Pat::Tuple(ps) | Pat::Variant(_, ps) | Pat::Or(ps) => ps.iter().any(|p| self.pat_moves(p)),
            _ => false,
        }
    }

    /// Emit tests; falls through on match, branches to `fail` otherwise.
    fn pat_test(&mut self, pat: &Pat, ptr: &str, ty: &Ty, fail: &str) {
        match pat {
            Pat::Wild | Pat::Bind(..) => {}
            Pat::Int(v) => {
                let t = self.llty(ty);
                let x = self.fresh();
                self.ins(&format!("{x} = load {t}, ptr {ptr}"));
                let c = self.fresh();
                self.ins(&format!("{c} = icmp eq {t} {x}, {v}"));
                self.cond_br(&c, fail);
            }
            Pat::Bool(b) => {
                let x = self.fresh();
                self.ins(&format!("{x} = load i1, ptr {ptr}"));
                let c = self.fresh();
                self.ins(&format!("{c} = icmp eq i1 {x}, {b}"));
                self.cond_br(&c, fail);
            }
            Pat::Range(lo, hi) => {
                let t = self.llty(ty);
                let signed = matches!(ty, Ty::Int(it) if it.signed());
                let x = self.fresh();
                self.ins(&format!("{x} = load {t}, ptr {ptr}"));
                let a = self.fresh();
                self.ins(&format!("{a} = icmp {} {t} {x}, {lo}", if signed { "sge" } else { "uge" }));
                let b = self.fresh();
                self.ins(&format!("{b} = icmp {} {t} {x}, {hi}", if signed { "sle" } else { "ule" }));
                let c = self.fresh();
                self.ins(&format!("{c} = and i1 {a}, {b}"));
                self.cond_br(&c, fail);
            }
            Pat::Tuple(ps) => {
                let Ty::Tuple(ts) = ty else { unreachable!() };
                let lt = self.llty(ty);
                for (i, (p, t)) in ps.iter().zip(ts).enumerate() {
                    if matches!(p, Pat::Wild | Pat::Bind(..)) {
                        continue;
                    }
                    let fp = self.fresh();
                    self.ins(&format!("{fp} = getelementptr inbounds {lt}, ptr {ptr}, i32 0, i32 {i}"));
                    self.pat_test(p, &fp, t, fail);
                }
            }
            Pat::Variant(idx, ps) => {
                let Ty::Adt(id, args) = ty else { unreachable!() };
                let a = &self.ck.adts[*id as usize];
                let lt = self.llty(ty);
                if a.is_enum() {
                    let disc = a.discriminants[*idx as usize];
                    let tag_ty = self.tag_ty(ty);
                    let tp = self.fresh();
                    self.ins(&format!("{tp} = getelementptr inbounds {lt}, ptr {ptr}, i32 0, i32 0"));
                    let tag = self.fresh();
                    self.ins(&format!("{tag} = load {tag_ty}, ptr {tp}"));
                    let c = self.fresh();
                    self.ins(&format!("{c} = icmp eq {tag_ty} {tag}, {disc}"));
                    self.cond_br(&c, fail);
                    if ps.iter().any(|p| !matches!(p, Pat::Wild | Pat::Bind(..))) {
                        let fields = self.ck.enum_variants(*id, args)[*idx as usize].clone();
                        let vty = self.struct_llty(&fields);
                        let pp = self.fresh();
                        self.ins(&format!("{pp} = getelementptr inbounds {lt}, ptr {ptr}, i32 0, i32 1"));
                        for (i, (p, t)) in ps.iter().zip(&fields).enumerate() {
                            if matches!(p, Pat::Wild | Pat::Bind(..)) {
                                continue;
                            }
                            let fp = self.fresh();
                            self.ins(&format!("{fp} = getelementptr inbounds {vty}, ptr {pp}, i32 0, i32 {i}"));
                            self.pat_test(p, &fp, t, fail);
                        }
                    }
                } else {
                    let fields = self.ck.struct_fields(*id, args);
                    for (i, (p, t)) in ps.iter().zip(&fields).enumerate() {
                        if matches!(p, Pat::Wild | Pat::Bind(..)) {
                            continue;
                        }
                        let fp = self.fresh();
                        self.ins(&format!("{fp} = getelementptr inbounds {lt}, ptr {ptr}, i32 0, i32 {i}"));
                        self.pat_test(p, &fp, t, fail);
                    }
                }
            }
            Pat::Or(alts) => {
                let ok = self.new_label("or_ok");
                for (i, alt) in alts.iter().enumerate() {
                    let next = if i + 1 == alts.len() { fail.to_string() } else { self.new_label("or_next") };
                    self.pat_test(alt, ptr, ty, &next);
                    self.br(&ok);
                    if i + 1 != alts.len() {
                        self.start(&next);
                    }
                }
                self.start(&ok);
            }
            Pat::Deref(inner) => {
                let Ty::Ref(t, _) = ty else { unreachable!() };
                let p2 = self.fresh();
                self.ins(&format!("{p2} = load ptr, ptr {ptr}"));
                self.pat_test(inner, &p2, t, fail);
            }
        }
    }

    fn cond_br(&mut self, c: &str, fail: &str) {
        let ok = self.new_label("m");
        self.term(&format!("br i1 {c}, label %{ok}, label %{fail}"));
        self.start(&ok);
    }

    /// Bind pattern variables from the value at `ptr`.
    fn pat_bind(&mut self, pat: &Pat, ptr: &str, ty: &Ty) {
        match pat {
            Pat::Bind(l, BindMode::Value) => {
                let lt = self.llty(ty);
                let v = self.fresh();
                self.ins(&format!("{v} = load {lt}, ptr {ptr}"));
                let lp = self.local_ptr(*l);
                self.ins(&format!("store {lt} {v}, ptr {lp}"));
                self.set_flag(*l, true);
            }
            Pat::Bind(l, BindMode::Ref(_)) => {
                let lp = self.local_ptr(*l);
                self.ins(&format!("store ptr {ptr}, ptr {lp}"));
            }
            Pat::Tuple(ps) => {
                let Ty::Tuple(ts) = ty else { unreachable!() };
                let lt = self.llty(ty);
                for (i, (p, t)) in ps.iter().zip(ts).enumerate() {
                    if !pat_has_binds(p) {
                        continue;
                    }
                    let fp = self.fresh();
                    self.ins(&format!("{fp} = getelementptr inbounds {lt}, ptr {ptr}, i32 0, i32 {i}"));
                    self.pat_bind(p, &fp, t);
                }
            }
            Pat::Variant(idx, ps) => {
                if !ps.iter().any(pat_has_binds) {
                    return;
                }
                let Ty::Adt(id, args) = ty else { unreachable!() };
                let lt = self.llty(ty);
                let (base, fields, sty) = if self.ck.adts[*id as usize].is_enum() {
                    let fields = self.ck.enum_variants(*id, args)[*idx as usize].clone();
                    let pp = self.fresh();
                    self.ins(&format!("{pp} = getelementptr inbounds {lt}, ptr {ptr}, i32 0, i32 1"));
                    let vty = self.struct_llty(&fields);
                    (pp, fields, vty)
                } else {
                    (ptr.to_string(), self.ck.struct_fields(*id, args), lt)
                };
                for (i, (p, t)) in ps.iter().zip(&fields).enumerate() {
                    if !pat_has_binds(p) {
                        continue;
                    }
                    let fp = self.fresh();
                    self.ins(&format!("{fp} = getelementptr inbounds {sty}, ptr {base}, i32 0, i32 {i}"));
                    self.pat_bind(p, &fp, t);
                }
            }
            Pat::Deref(inner) => {
                if !pat_has_binds(inner) {
                    return;
                }
                let Ty::Ref(t, _) = ty else { unreachable!() };
                let p2 = self.fresh();
                self.ins(&format!("{p2} = load ptr, ptr {ptr}"));
                self.pat_bind(inner, &p2, t);
            }
            _ => {}
        }
    }

    /// After a moving match/destructure, destroy the parts not bound by value.
    fn drop_unbound(&mut self, pat: &Pat, ptr: &str, ty: &Ty) {
        if !self.needs_drop(ty) {
            return;
        }
        match pat {
            Pat::Wild | Pat::Bind(_, BindMode::Ref(_)) => self.drop_at(ptr, ty),
            Pat::Bind(_, BindMode::Value) => {}
            Pat::Tuple(ps) => {
                let Ty::Tuple(ts) = ty else { return };
                let lt = self.llty(ty);
                for (i, (p, t)) in ps.iter().zip(ts).enumerate() {
                    if !self.needs_drop(t) {
                        continue;
                    }
                    let fp = self.fresh();
                    self.ins(&format!("{fp} = getelementptr inbounds {lt}, ptr {ptr}, i32 0, i32 {i}"));
                    self.drop_unbound(p, &fp, t);
                }
            }
            Pat::Variant(idx, ps) => {
                let Ty::Adt(id, args) = ty else { return };
                if self.ck.adts[*id as usize].drop_impl.is_some() {
                    return;
                }
                let lt = self.llty(ty);
                let (base, fields, sty) = if self.ck.adts[*id as usize].is_enum() {
                    let fields = self.ck.enum_variants(*id, args)[*idx as usize].clone();
                    let pp = self.fresh();
                    self.ins(&format!("{pp} = getelementptr inbounds {lt}, ptr {ptr}, i32 0, i32 1"));
                    let vty = self.struct_llty(&fields);
                    (pp, fields, vty)
                } else {
                    (ptr.to_string(), self.ck.struct_fields(*id, args), lt)
                };
                for (i, (p, t)) in ps.iter().zip(&fields).enumerate() {
                    if !self.needs_drop(t) {
                        continue;
                    }
                    let fp = self.fresh();
                    self.ins(&format!("{fp} = getelementptr inbounds {sty}, ptr {base}, i32 0, i32 {i}"));
                    self.drop_unbound(p, &fp, t);
                }
            }
            _ => {}
        }
    }

    // --------------------------------------------------------- constants

    fn const_val(&mut self, v: &ConstVal, ty: &Ty) -> String {
        match (v, ty) {
            (ConstVal::Int(n), Ty::Float(f)) => float_lit(*n as f64, *f),
            (ConstVal::Int(n), _) => n.to_string(),
            (ConstVal::Float(f), Ty::Float(ft)) => float_lit(*f, *ft),
            (ConstVal::Float(f), _) => float_lit(*f, FloatTy::F64),
            (ConstVal::Bool(b), _) => b.to_string(),
            (ConstVal::Str(s), _) => {
                let g = self.string(s);
                format!("{{ ptr {g}, {} {} }}", self.usize_ty(), s.len())
            }
            (ConstVal::Array(items), Ty::Array(et, _)) => {
                let et_l = self.llty(et);
                let parts: Vec<String> = items.iter().map(|i| format!("{et_l} {}", self.const_val(i, et))).collect();
                format!("[{}]", parts.join(", "))
            }
            (ConstVal::Repeat(item, n), Ty::Array(et, _)) => {
                let iv = self.const_val(item, et);
                if *n == 0 || iv == "0" || iv == "false" || iv == "0x0000000000000000" {
                    return "zeroinitializer".into();
                }
                let et_l = self.llty(et);
                let parts: Vec<String> = (0..*n).map(|_| format!("{et_l} {iv}")).collect();
                format!("[{}]", parts.join(", "))
            }
            (ConstVal::Tuple(items), Ty::Tuple(ts)) => {
                if items.is_empty() {
                    return "zeroinitializer".into();
                }
                let parts: Vec<String> = items.iter().zip(ts).map(|(i, t)| format!("{} {}", self.llty(t), self.const_val(i, t))).collect();
                format!("{{ {} }}", parts.join(", "))
            }
            _ => "zeroinitializer".into(),
        }
    }
}

fn rty_bits(t: &Ty, ptr_bits: u32) -> u32 {
    match t {
        Ty::Int(it) => it.bits(ptr_bits),
        _ => ptr_bits,
    }
}

fn pat_has_binds(p: &Pat) -> bool {
    match p {
        Pat::Bind(..) => true,
        Pat::Tuple(ps) | Pat::Variant(_, ps) | Pat::Or(ps) => ps.iter().any(pat_has_binds),
        Pat::Deref(inner) => pat_has_binds(inner),
        _ => false,
    }
}

